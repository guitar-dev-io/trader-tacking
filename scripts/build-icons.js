// Vendors the Lucide icons the app uses into icons.js (between the <lucide> markers).
// Run: node scripts/build-icons.js   (needs devDependency lucide-static)
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const NAMES = ['wallet', 'trending-up', 'trending-down', 'percent', 'scale', 'timer', 'sigma', 'chart-area', 'filter', 'arrow-up-down', 'activity', 'banknote', 'calendar-range', 'lock', 'lock-open', 'log-in', 'book-open', 'graduation-cap', 'globe', 'monitor', 'rocket', 'download', 'circle-check',
  'hourglass', 'triangle-alert', 'chart-line', 'file-text', 'folder-open', 'clipboard-copy', 'pencil', 'save', 'star', 'newspaper',
  'target', 'camera', 'settings', 'rewind', 'skip-back', 'skip-forward', 'play', 'pause', 'octagon-x', 'circle-x', 'flask-conical',
  'eye', 'eye-off', 'brush-cleaning', 'chart-column', 'coins', 'sparkles', 'bell', 'undo-2', 'redo-2', 'trash-2', 'layers', 'magnet',
  'calculator', 'list', 'scroll-text', 'maximize', 'zoom-in', 'minus', 'plus', 'chevron-left', 'chevron-right', 'rotate-ccw', 'menu',
  'brain', 'refresh-cw', 'x', 'info', 'shield-check', 'external-link', 'check', 'plug', 'smartphone', 'copy', 'circle-play', 'type',
  'arrow-up', 'arrow-down', 'sun-moon', 'house', 'wifi-off', 'loader-circle', 'chart-candlestick', 'compass', 'landmark', 'shield', 'library', 'search', 'clock', 'list-checks', 'route', 'circle-dashed', 'arrow-left', 'table-2', 'calendar-days', 'trophy', 'flame', 'book-marked'];
const dir = path.join(root, 'node_modules', 'lucide-static', 'icons');
const ver = require(path.join(root, 'node_modules', 'lucide-static', 'package.json')).version;
const out = NAMES.map((n) => {
  const s = fs.readFileSync(path.join(dir, n + '.svg'), 'utf8');
  const inner = s.slice(s.indexOf('>', s.indexOf('<svg')) + 1, s.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>');
  return `    '${n}': '${inner.replace(/'/g, "\\'")}',`;
});
const f = path.join(root, 'icons.js');
let src = fs.readFileSync(f, 'utf8');
const block = `  // <lucide> generated by scripts/build-icons.js from lucide-static ${ver} — Lucide icons, ISC License, (c) Lucide Contributors (https://lucide.dev/license)\n  const L = {\n${out.join('\n')}\n  };\n  // </lucide>`;
src = src.replace(/  \/\/ <lucide>[\s\S]*?\/\/ <\/lucide>/, block);
fs.writeFileSync(f, src);
console.log('icons.js: ' + NAMES.length + ' Lucide icons');

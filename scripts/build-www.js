// Copies the shared UI into www/ for the Android (Capacitor) app and plain-browser use.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), out = path.join(root, 'www');
const files = ['index.html', 'style.css', 'lessons-guide.css', 'mm.css', 'mobile.css', 'setup.css', 'positions.css', 'pages.css', 'about.css', 'learn-center.css', 'dashboard.css', 'vcg-inject.js', 'bridge.js', 'indicators.js', 'analysis.js', 'bounce.js', 'custom.js', 'lessons.js', 'lessons-guide.js', 'icons.js',
  'app-core.js', 'app-chart.js', 'app-analysis.js', 'app-bounce.js', 'app-data.js', 'app-overlay.js', 'mm.js', 'mm-learn.js', 'app.js', 'draw.js', 'planner.js', 'settings.js', 'extras.js', 'learn.js', 'news.js', 'setup.js', 'positions.js', 'mtf.js', 'ui.js', 'mobile.js', 'pages.js', 'about.js', 'dashboard.js', 'learn-center.js', 'news-page.js', 'claude-bridge.js', 'pwa.js'];
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'lib'), { recursive: true });
const version = require(path.join(root, 'package.json')).version;
for (const f of files) {
  let s = fs.readFileSync(path.join(root, f), 'utf8');
  if (f === 'index.html') {
    s = s.replace('<script src="vcg-inject.js"></script>', '<script src="version.js"></script>\n<script src="capacitor.js"></script>\n<script src="vcg-inject.js"></script>')
      // no viewport-fit=cover: Capacitor then pads the WebView so nothing is drawn under the Android status/gesture bars
      .replace('<meta charset="UTF-8">', '<meta charset="UTF-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1">')
      // the app's local pages don't need a CSP here (and it must never block Capacitor's own bridge script)
      .replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\n?/, '')
      // web app (PWA): installable from the browser; pwa.js does nothing inside the Android app
      .replace('</head>', '<link rel="manifest" href="manifest.webmanifest">\n<meta name="theme-color" content="#0f1115">\n<link rel="apple-touch-icon" href="assets/icon-192.png">\n<meta name="apple-mobile-web-app-capable" content="yes">\n<meta name="apple-mobile-web-app-title" content="Price Tracker">\n</head>')
      .replace('<script src="claude-bridge.js"></script>', '<script src="claude-bridge.js"></script>\n<script src="pwa.js"></script>');
  }
  fs.writeFileSync(path.join(out, f), s);
}
for (const f of fs.readdirSync(path.join(root, 'lib'))) fs.copyFileSync(path.join(root, 'lib', f), path.join(out, 'lib', f));
fs.copyFileSync(path.join(root, 'build', 'icon.png'), path.join(out, 'icon.png'));
fs.cpSync(path.join(root, 'assets'), path.join(out, 'assets'), { recursive: true });
// @capacitor/core: provides Capacitor.registerPlugin() on top of the native bridge the Android WebView injects
fs.copyFileSync(require.resolve('@capacitor/core/dist/capacitor.js'), path.join(out, 'capacitor.js'));
fs.writeFileSync(path.join(out, 'version.js'), `window.APP_VERSION = '${version}';\n`);
// ---- PWA: manifest + service worker (cache the app shell, version-stamped so a new deploy replaces it)
fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify({
  name: 'Price Tracker — ราคา กราฟ และบทเรียน Price Action', short_name: 'Price Tracker', lang: 'th', start_url: './', scope: './',
  display: 'standalone', background_color: '#0f1115', theme_color: '#0f1115', description: 'กราฟ วิเคราะห์ จุดเด้ง เครื่องคำนวณ lot และบทเรียน — อ่านราคาอย่างเดียว ไม่ส่งคำสั่งซื้อขาย',
  icons: [{ src: 'assets/icon-192.png', sizes: '192x192', type: 'image/png' }, { src: 'assets/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'assets/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }],
}, null, 2));
const shell = ['./', 'index.html', 'version.js', 'capacitor.js', 'manifest.webmanifest', ...files.filter((f) => f !== 'index.html'),
  ...fs.readdirSync(path.join(out, 'lib')).map((f) => 'lib/' + f), ...fs.readdirSync(path.join(out, 'assets')).map((f) => 'assets/' + f)];
fs.writeFileSync(path.join(out, 'sw.js'), `// generated by scripts/build-www.js
const CACHE = 'pt-${version}-${Date.now().toString(36)}', SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin) return;          // market data, news: always network
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((r) => r || fetch(e.request).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('index.html'))));
});
`);
console.log(`www/ built (v${version}, ${files.length} files)`);
